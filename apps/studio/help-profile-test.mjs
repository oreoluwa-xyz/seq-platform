import assert from 'node:assert/strict';
import {identityProfile,readHelpIdentity,spaceGuide,adaptControlHelp,profileSections,renderSpaceHint} from './help-profile.mjs';
import {controlsFor} from './keyboard.mjs';
const target='keychron/v1_max/ansi_encoder:seq_test';
for(const [version,profile] of [['2026.10.15.3','legacy'],['2026.10.16.1','length'],['2026.10.16.2','current'],['2027.1.1','unknown']])assert.equal(identityProfile({target,version}),profile);
assert.equal(identityProfile({target:'other',version:'2026.10.16.2'}),'unknown');
assert.equal(identityProfile(null),'unknown');
assert.equal(await readHelpIdentity({request:async()=>{throw Error('unsupported');}}),null);
assert.equal(await readHelpIdentity({request:async()=>new Uint8Array(1)}),null);
const bytes=new Uint8Array(113);for(const [offset,value] of [[0,'SEQFWID1'],[8,'2026.10.16.2'],[32,target],[80,'1234567890abcdef1234567890abcdef']])bytes.set(new TextEncoder().encode(value),offset);
const calls=[];const identity=await readHelpIdentity({request:async(cmd,obj=0,offset=0)=>{calls.push([cmd,obj,offset]);return bytes.slice(offset,offset+64);}});
assert.equal(identityProfile(identity),'current');assert.deepEqual(calls,[[24,0,0],[24,0,64]]);
const current=controlsFor('navigation'),legacy=adaptControlHelp(current,'navigation','legacy');
assert.equal(legacy.F,undefined);assert.equal(legacy['='].label,'Follow');assert.equal(current.F.label,'Follow');assert.equal(current['='].label,'Double length');
assert.match(adaptControlHelp(current,'navigation','length').F1.detail,/unavailable/);
assert.match(adaptControlHelp(current,'navigation','unknown').Knob.detail,/not verified/);
assert(spaceGuide('current').some(([key])=>key==='Shift + Space + F1–F12'));
assert(!spaceGuide('length').some(([key])=>key==='Shift + Space + F1–F12'));
const sections=[{title:'Track length with the knob',lines:['Current length controls']},{title:'Mutes',lines:['Current mute controls']}];
assert.match(profileSections(sections,'legacy')[0].lines.join(' '),/unavailable/);
assert.deepEqual(profileSections(sections,'current'),sections);
console.log('Feature-aware help: known/unknown identities, read failures, version boundaries, immutable controls and written reference passed.');

